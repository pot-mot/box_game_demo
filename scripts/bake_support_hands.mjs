import fs from 'node:fs'
import path from 'node:path'

/* 生成器在 Node 下运行：材质纹理需要 DOM canvas；无 2D 上下文时材质库会安全回退为无纹理。 */
const fakeCanvas = () => ({
    width: 0,
    height: 0,
    getContext: () => null,
})
globalThis.document = {
    createElement: tag => (tag === 'canvas' ? fakeCanvas() : {}),
}

await import('../src/entity/character/body_form/index.ts')
const {BASE_POSE_SAMPLERS} = await import('../src/entity/character/forms/humanoid/pose_fns.ts')
const {buildBaseClip} = await import('../src/entity/character/forms/humanoid/clips/base_clips.ts')
const {ATTACK_CLIPS} = await import('../src/character/weapon/attack_clips/index.ts')
const {compileAttackClip} = await import('../src/entity/character/forms/humanoid/clips/attack_clip_build.ts')
const {clipFromJSON} = await import('../src/skeleton/anim/serialization.ts')
const {
    TWO_HANDED_WEAPONS,
    bakeSupportHandToGrip,
    computeSupportHandFingerprint,
    extractSupportTracks,
    isTwoHandedAttackClip,
    supportGripLocalOf,
    weaponOfClip,
} = await import('../src/entity/character/forms/humanoid/clips/support_hand_bake.ts')

const outDir = path.resolve('src/entity/character/forms/humanoid/clips/generated')

const base = {}
for (const weapon of TWO_HANDED_WEAPONS) {
    const gripLocal = supportGripLocalOf(weapon)
    if (gripLocal === undefined) continue
    const states = {}
    for (const state of Object.keys(BASE_POSE_SAMPLERS)) {
        const clip = buildBaseClip(state, true, 0, 'right')
        const baked = bakeSupportHandToGrip(clip, gripLocal, false)
        const tracks = extractSupportTracks(baked)
        if (tracks !== undefined) states[state] = tracks
    }
    base[weapon.classId] = states
}

const attacks = {}
for (const clipId of Object.keys(ATTACK_CLIPS)) {
    if (!isTwoHandedAttackClip(clipId)) continue
    const weapon = weaponOfClip(clipId)
    if (weapon === undefined) continue
    const gripLocal = supportGripLocalOf(weapon)
    if (gripLocal === undefined) continue
    const body = clipFromJSON(compileAttackClip(clipId, ATTACK_CLIPS[clipId]))
    const tracks = extractSupportTracks(bakeSupportHandToGrip(body, gripLocal, true))
    if (tracks !== undefined) attacks[clipId] = tracks
}

const header = `/**\n * AUTO-GENERATED by scripts/bake_support_hands.mjs — 禁止手改。\n * 修改 pose_fns / 武器网格 / 基础状态时长后运行 pnpm bake:support-hands。\n */\n`

fs.writeFileSync(
    path.join(outDir, 'support_hand_base.ts'),
    `${header}import type {SupportHandTable} from '../support_hand_merge.ts'\n\nexport const SUPPORT_HAND_BASE: SupportHandTable = ${JSON.stringify(base)}\n`,
    'utf8',
)
fs.writeFileSync(
    path.join(outDir, 'support_hand_attacks.ts'),
    `${header}import type {SupportHandTrackData} from '../support_hand_merge.ts'\n\nexport const SUPPORT_HAND_ATTACKS: Readonly<Record<string, SupportHandTrackData>> = ${JSON.stringify(attacks)}\n`,
    'utf8',
)
fs.writeFileSync(
    path.join(outDir, 'support_hand_fingerprint.ts'),
    `${header}export const SUPPORT_HAND_BAKE_FINGERPRINT = '${computeSupportHandFingerprint()}'\n`,
    'utf8',
)
console.log(`base=${Object.keys(base).length} attacks=${Object.keys(attacks).length}`)
